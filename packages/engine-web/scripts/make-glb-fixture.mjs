// Generates dev/fixtures/box-character.glb: a tiny offline test character
// (two boxes: body and head) with named `idle` and `walk` animations.
//
//   node scripts/make-glb-fixture.mjs
//
// Written from scratch by this script, dedicated to the public domain
// (CC0-1.0); no third-party asset data. Used by the playground `model=`
// parameter, the `glb-character-town-day` screenshot and the character tests.
import { mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Document, NodeIO } from '@gltf-transform/core';

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'dev', 'fixtures', 'box-character.glb');

/** Box with flat normals: min/max corners → positions, normals, indices. */
function box([x0, y0, z0], [x1, y1, z1]) {
  const faces = [
    [[1, 0, 0], [[x1, y0, z1], [x1, y0, z0], [x1, y1, z0], [x1, y1, z1]]],
    [[-1, 0, 0], [[x0, y0, z0], [x0, y0, z1], [x0, y1, z1], [x0, y1, z0]]],
    [[0, 1, 0], [[x0, y1, z1], [x1, y1, z1], [x1, y1, z0], [x0, y1, z0]]],
    [[0, -1, 0], [[x0, y0, z0], [x1, y0, z0], [x1, y0, z1], [x0, y0, z1]]],
    [[0, 0, 1], [[x0, y0, z1], [x1, y0, z1], [x1, y1, z1], [x0, y1, z1]]],
    [[0, 0, -1], [[x1, y0, z0], [x0, y0, z0], [x0, y1, z0], [x1, y1, z0]]],
  ];
  const pos = [], nor = [], idx = [];
  faces.forEach(([n, quad], f) => {
    for (const v of quad) { pos.push(...v); nor.push(...n); }
    const b = f * 4;
    idx.push(b, b + 1, b + 2, b, b + 2, b + 3);
  });
  return { pos, nor, idx };
}

const doc = new Document();
doc.getRoot().getAsset().copyright = 'CC0-1.0 (generated by packages/engine-web/scripts/make-glb-fixture.mjs)';
doc.getRoot().getAsset().generator = 'maprama make-glb-fixture';
const buffer = doc.createBuffer();

function boxMesh(name, min, max, color) {
  const g = box(min, max);
  const prim = doc.createPrimitive()
    .setAttribute('POSITION', doc.createAccessor().setType('VEC3').setArray(new Float32Array(g.pos)).setBuffer(buffer))
    .setAttribute('NORMAL', doc.createAccessor().setType('VEC3').setArray(new Float32Array(g.nor)).setBuffer(buffer))
    .setIndices(doc.createAccessor().setType('SCALAR').setArray(new Uint16Array(g.idx)).setBuffer(buffer))
    .setMaterial(doc.createMaterial(`${name}-material`).setBaseColorFactor(color).setRoughnessFactor(0.8));
  return doc.createMesh(name).addPrimitive(prim);
}

const root = doc.createNode('box-character');
const body = doc.createNode('body').setMesh(boxMesh('body', [-0.3, 0, -0.2], [0.3, 1.2, 0.2], [0.95, 0.55, 0.2, 1]));
const head = doc.createNode('head').setMesh(boxMesh('head', [-0.22, 0, -0.22], [0.22, 0.44, 0.22], [0.98, 0.85, 0.7, 1])).setTranslation([0, 1.25, 0]);
root.addChild(body).addChild(head);
doc.createScene('scene').addChild(root);

const input = (times) => doc.createAccessor().setType('SCALAR').setArray(new Float32Array(times)).setBuffer(buffer);
const output = (type, values) => doc.createAccessor().setType(type).setArray(new Float32Array(values)).setBuffer(buffer);
const quatY = (a) => [0, Math.sin(a / 2), 0, Math.cos(a / 2)];
const quatZ = (a) => [0, 0, Math.sin(a / 2), Math.cos(a / 2)];

// idle: slow breathing (body scale) over 2 s
{
  const s = doc.createAnimationSampler().setInput(input([0, 1, 2])).setOutput(output('VEC3', [1, 1, 1, 1, 1.04, 1, 1, 1, 1])).setInterpolation('LINEAR');
  const c = doc.createAnimationChannel().setTargetNode(body).setTargetPath('scale').setSampler(s);
  doc.createAnimation('idle').addSampler(s).addChannel(c);
}
// walk: body sway and head bob over 0.6 s
{
  const t = [0, 0.15, 0.3, 0.45, 0.6];
  const sway = doc.createAnimationSampler().setInput(input(t)).setOutput(output('VEC4', [...quatZ(0), ...quatZ(0.12), ...quatZ(0), ...quatZ(-0.12), ...quatZ(0)])).setInterpolation('LINEAR');
  const turn = doc.createAnimationSampler().setInput(input(t)).setOutput(output('VEC4', [...quatY(0), ...quatY(0.15), ...quatY(0), ...quatY(-0.15), ...quatY(0)])).setInterpolation('LINEAR');
  const bob = doc.createAnimationSampler().setInput(input(t)).setOutput(output('VEC3', [0, 1.25, 0, 0, 1.31, 0, 0, 1.25, 0, 0, 1.31, 0, 0, 1.25, 0])).setInterpolation('LINEAR');
  doc.createAnimation('walk')
    .addSampler(sway).addSampler(turn).addSampler(bob)
    .addChannel(doc.createAnimationChannel().setTargetNode(body).setTargetPath('rotation').setSampler(sway))
    .addChannel(doc.createAnimationChannel().setTargetNode(root).setTargetPath('rotation').setSampler(turn))
    .addChannel(doc.createAnimationChannel().setTargetNode(head).setTargetPath('translation').setSampler(bob));
}

mkdirSync(dirname(out), { recursive: true });
await new NodeIO().write(out, doc);
console.log(`wrote ${out}`);
