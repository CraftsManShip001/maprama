#!/usr/bin/env node
/**
 * Generates `cpp/src/ThemeData.cpp`: the built-in theme data of `@maprama/protocol` (PRESETS, TIMES, CINE,
 * PRESET_DEFAULTS, BASE_THEME_DEFAULTS) embedded as one JSON string for the C++ `ThemeResolver`.
 *
 * The protocol package stays the single source of truth: the file is generated from its build output and
 * `npm test` runs this script with `--check`, which fails when the committed file is out of date.
 *
 *   node scripts/generate-theme-data.mjs          # (re)write cpp/src/ThemeData.cpp
 *   node scripts/generate-theme-data.mjs --check  # exit 1 when it differs from the protocol data
 *
 * Run `npm run build -w @maprama/protocol` first.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as P from '@maprama/protocol';

const outPath = fileURLToPath(new URL('../cpp/src/ThemeData.cpp', import.meta.url));
const check = process.argv.includes('--check');

const data = {
  presets: P.PRESETS,
  times: P.TIMES,
  cine: P.CINE,
  presetDefaults: P.PRESET_DEFAULTS,
  baseDefaults: P.BASE_THEME_DEFAULTS,
};

// One member per line keeps diffs of the generated file readable.
const body = Object.entries(data)
  .map(([key, value]) => `${JSON.stringify(key)}:${JSON.stringify(value)}`)
  .join(',\n');
if (body.includes(')json"')) throw new Error('generate-theme-data: theme data contains the raw-string delimiter');

const text = `// GENERATED by scripts/generate-theme-data.mjs from @maprama/protocol — do not edit.
// Built-in theme data (PRESETS, TIMES, CINE, PRESET_DEFAULTS, BASE_THEME_DEFAULTS) for ThemeResolver.
#include "theme_data.hpp"

namespace maprama::theme_data {

const char* const kBuiltInThemeJson = R"json({
${body}
})json";

}  // namespace maprama::theme_data
`;

if (check) {
  let current = '';
  try {
    current = readFileSync(outPath, 'utf8');
  } catch {
    // missing file: reported below
  }
  if (current !== text) {
    console.error('generate-theme-data: cpp/src/ThemeData.cpp is out of date; run `node scripts/generate-theme-data.mjs`');
    process.exit(1);
  }
  console.log('generate-theme-data: cpp/src/ThemeData.cpp matches @maprama/protocol');
} else {
  writeFileSync(outPath, text);
  console.log(`generate-theme-data: wrote ${outPath}`);
}
