// Builds the service API reference from services/api/openapi.yaml (read-only):
//   - public/service/openapi.html: Redoc static page (redocly build-docs), with the
//     Redoc bundle served from our own site instead of a CDN;
//   - service/_endpoints.md: an endpoint table included by service/api-reference.md.
import { spawnSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const docs = join(dirname(fileURLToPath(import.meta.url)), '..');
const spec = join(docs, '..', 'services', 'api', 'openapi.yaml');
const outDir = join(docs, 'public', 'service');
mkdirSync(outDir, { recursive: true });

// ---- Redoc static HTML ----
const html = join(outDir, 'openapi.html');
const bin = join(docs, 'node_modules', '.bin', process.platform === 'win32' ? 'redocly.cmd' : 'redocly');
const r = spawnSync(bin, ['build-docs', spec, '-o', html, '--title', 'Maprama API reference', '--disableGoogleFont', '--lint-config', 'off'], {
  cwd: docs,
  encoding: 'utf8',
});
if (r.status !== 0) {
  process.stderr.write(r.stdout + r.stderr);
  console.error(`gen-openapi: redocly build-docs failed (exit ${r.status ?? r.signal})`);
  process.exit(1);
}
copyFileSync(join(docs, 'node_modules', 'redoc', 'bundles', 'redoc.standalone.js'), join(outDir, 'redoc.standalone.js'));
const page = readFileSync(html, 'utf8');
const localized = page.replace(/<script src="https:\/\/cdn\.redocly\.com\/redoc\/[^"]+\/redoc\.standalone\.js"/, '<script src="./redoc.standalone.js"');
if (localized === page) {
  console.error('gen-openapi: could not find the Redoc CDN script tag to replace');
  process.exit(1);
}
writeFileSync(html, localized);

// ---- endpoint table ----
const doc = parse(readFileSync(spec, 'utf8'));
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/[{}<>]/g, (c) => `&#${c.charCodeAt(0)};`);
const rows = [];
for (const [path, item] of Object.entries(doc.paths ?? {})) {
  for (const [method, op] of Object.entries(item)) {
    if (!['get', 'post', 'put', 'patch', 'delete'].includes(method)) continue;
    const security = op.security ?? doc.security ?? [];
    const auth = security.length === 0 ? '없음' : security.map((s) => Object.keys(s).join('+')).join(' 또는 ');
    rows.push(`| \`${method.toUpperCase()}\` | \`${cell(path)}\` | ${cell((op.tags ?? []).join(', '))} | ${cell(op.summary)} | \`${cell(op.operationId)}\` | ${cell(auth)} |`);
  }
}
const md = [
  '<!-- generated by docs/scripts/gen-openapi.mjs from services/api/openapi.yaml; do not edit -->',
  '',
  `OpenAPI \`${cell(doc.openapi)}\` · API 버전 \`${cell(doc.info?.version)}\``,
  '',
  '| 메서드 | 경로 | 태그 | 요약 | operationId | 인증 |',
  '| --- | --- | --- | --- | --- | --- |',
  ...rows,
  '',
].join('\n');
writeFileSync(join(docs, 'service', '_endpoints.md'), md);
console.log(`gen-openapi: wrote public/service/openapi.html and service/_endpoints.md (${rows.length} operations)`);
